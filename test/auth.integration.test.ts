import { test } from "node:test";
import assert from "node:assert/strict";
import Fastify from "fastify";
import { MongoClient } from "mongodb";
import bcrypt from "bcryptjs";
import { authPlugin } from "../src/plugins/auth/auth.plugin.js";
import { organizationsPlugin } from "../src/plugins/organizations/organizations.plugin.js";
import { BeeEventBus } from "../src/core/event-bus.js";
import type { BeeContext, BeeLogger } from "../src/core/types.js";

const uri = process.env.MONGODB_TEST_URI;
test("auth integration: login, token introspection, refresh rotation and logout", { skip: !uri }, async () => {
  const dbName = "bee_core_test_" + Date.now();
  const client = new MongoClient(uri!);
  await client.connect();
  const db = client.db(dbName);
  const passwordHash = await bcrypt.hash("Test-password-12345", 10);
  await db.collection("tenants").insertMany([{id:"tenant-alpha",name:"Alpha",domains:["alpha.example.test"],createdAt:new Date()},{id:"tenant-beta",name:"Beta",domains:["beta.example.test"],createdAt:new Date()},{id:"tenant-legacy",name:"Legacy",createdAt:new Date()}]);
  await db.collection("users").insertMany([{ id: "test-user", email: "test@example.com", passwordHash, roles: ["admin"], enabled: true, allowedClients: ["dashboard"], tenantId:"tenant-alpha", createdAt: new Date(), updatedAt: new Date() },{ id:"test-user-beta",email:"beta@example.com",passwordHash,roles:["user"],enabled:true,allowedClients:["dashboard"],tenantId:"tenant-beta",createdAt:new Date(),updatedAt:new Date() },{id:"legacy-user",email:"legacy@example.com",passwordHash,roles:["user"],enabled:true,allowedClients:["dashboard"],tenantId:"tenant-legacy",createdAt:new Date(),updatedAt:new Date()}]);
  await db.collection("template_preferences").createIndex({userId:1},{unique:true,name:"template_preferences_user_unique"});
  await db.collection("template_preferences").insertOne({userId:"legacy-user",public:"editorial",dashboard:"paper",updatedAt:new Date()});
  const app = Fastify();
  const logger: BeeLogger = { info(){}, warn(){}, error(){} };
  const ctx: BeeContext = { appName: "Bee test", version: "test", events: new BeeEventBus(), logger, server: app, config: { jwtSecret: "01234567890123456789012345678901", mongoUri: uri!, mongoDbName: dbName, authAdminEmail: "", authAdminPassword: "" } };
  try {
    await authPlugin.initialize?.(ctx);
    await organizationsPlugin.initialize?.(ctx);
    await app.ready();
    const bad = await app.inject({ method: "POST", url: "/auth/login", payload: { email: "test@example.com", password: "wrong", client: "dashboard" } });
    assert.equal(bad.statusCode, 401);
    const denied = await app.inject({ method: "POST", url: "/auth/login", payload: { email: "test@example.com", password: "Test-password-12345", client: "public" } });
    assert.equal(denied.statusCode, 403);
    const login = await app.inject({ method: "POST", url: "/auth/login", payload: { email: "test@example.com", password: "Test-password-12345", client: "dashboard" } });
    assert.equal(login.statusCode, 200);
    const tokens = login.json();
    assert.ok(tokens.accessToken); assert.ok(tokens.refreshToken);
    const publicTicket = await app.inject({method:"POST",url:"/templates/public-stream-ticket",headers:{host:"alpha.example.test"}});
    assert.equal(publicTicket.statusCode,200);
    assert.ok(publicTicket.json().ticket);
    const publicAlpha = await app.inject({method:"GET",url:"/templates/public",headers:{host:"alpha.example.test"}});
    assert.equal(publicAlpha.statusCode,200);
    assert.equal(publicAlpha.json().tenantId,"tenant-alpha");
    const setAlphaDomains = await app.inject({method:"PUT",url:"/tenants/domains",headers:{authorization:"Bearer "+tokens.accessToken},payload:{domains:["www.alpha.example.test"]}});
    assert.equal(setAlphaDomains.statusCode,200);
    const publicUpdatedDomain = await app.inject({method:"GET",url:"/templates/public",headers:{host:"www.alpha.example.test"}});
    assert.equal(publicUpdatedDomain.json().tenantId,"tenant-alpha");
    const defaultTemplates = await app.inject({ method: "GET", url: "/templates/preferences", headers: { authorization: "Bearer " + tokens.accessToken } });
    assert.equal(defaultTemplates.statusCode, 200);
    assert.equal(defaultTemplates.json().tenantId,"tenant-alpha");
    assert.deepEqual(defaultTemplates.json().selection, { public: "aurora", dashboard: "midnight" });
    assert.deepEqual(defaultTemplates.json().installedTemplates.sort(),["aurora","editorial","midnight","paper"]);
    const catalog = await app.inject({method:"GET",url:"/templates/catalog",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.equal(catalog.statusCode,200);
    assert.ok(catalog.json().catalog.some((item:{id:string})=>item.id==="studio"));
    const activateUninstalled = await app.inject({method:"PUT",url:"/templates/preferences",headers:{authorization:"Bearer "+tokens.accessToken},payload:{public:"studio"}});
    assert.equal(activateUninstalled.statusCode,400);
    const installStudio = await app.inject({method:"POST",url:"/templates/install",headers:{authorization:"Bearer "+tokens.accessToken},payload:{templateId:"studio"}});
    assert.equal(installStudio.statusCode,200);
    assert.ok(installStudio.json().installedTemplates.includes("studio"));
    const rejectUnknownPackage = await app.inject({method:"POST",url:"/templates/install",headers:{authorization:"Bearer "+tokens.accessToken},payload:{templateId:"remote-code"}});
    assert.equal(rejectUnknownPackage.statusCode,404);
    const saveTemplates = await app.inject({ method: "PUT", url: "/templates/preferences", headers: { authorization: "Bearer " + tokens.accessToken }, payload: { public: "editorial", dashboard: "paper" } });
    assert.equal(saveTemplates.statusCode, 200);
    assert.deepEqual(saveTemplates.json().selection, { public: "editorial", dashboard: "paper" });
    const readTemplates = await app.inject({ method: "GET", url: "/templates/preferences", headers: { authorization: "Bearer " + tokens.accessToken } });
    assert.deepEqual(readTemplates.json().selection, { public: "editorial", dashboard: "paper" });
    const defaultTheme = await app.inject({method:"GET",url:"/templates/theme",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.equal(defaultTheme.statusCode,200);
    assert.equal(defaultTheme.json().tokens["--bg"],"#080a12");
    const saveTheme = await app.inject({method:"PUT",url:"/templates/theme",headers:{authorization:"Bearer "+tokens.accessToken},payload:{tokens:{"--bg":"#112233","--purple":"#abcdef"}}});
    assert.equal(saveTheme.statusCode,200);
    assert.equal(saveTheme.json().tokens["--bg"],"#112233");
    const readTheme = await app.inject({method:"GET",url:"/templates/theme",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.equal(readTheme.json().tokens["--purple"],"#abcdef");
    const unsafeTheme = await app.inject({method:"PUT",url:"/templates/theme",headers:{authorization:"Bearer "+tokens.accessToken},payload:{tokens:{"--bg":"red;body{display:none}"}}});
    assert.equal(unsafeTheme.statusCode,400);
    const streamTicket = await app.inject({method:"POST",url:"/templates/stream-ticket",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.equal(streamTicket.statusCode,200);
    assert.ok(streamTicket.json().ticket);
    const invalidStream = await app.inject({method:"GET",url:"/templates/events?ticket=invalid-ticket"});
    assert.equal(invalidStream.statusCode,401);
    const listenAddress = await app.listen({port:0,host:"127.0.0.1"});
    const liveResponse = await fetch(listenAddress + "/templates/events?ticket=" + streamTicket.json().ticket);
    assert.equal(liveResponse.status,200);
    assert.match(liveResponse.headers.get("content-type") || "",/text\/event-stream/);
    const liveReader = liveResponse.body!.getReader();
    let initialText = "";
    while (!initialText.includes('"type":"snapshot"')) {
      const chunk = await liveReader.read();
      assert.equal(chunk.done, false, "SSE stream closed before initial snapshot");
      initialText += new TextDecoder().decode(chunk.value);
    }
    assert.match(initialText,/"installedTemplates"/);
    const liveThemeUpdate = await app.inject({method:"PUT",url:"/templates/theme",headers:{authorization:"Bearer "+tokens.accessToken},payload:{tokens:{"--bg":"#334455"}}});
    assert.equal(liveThemeUpdate.statusCode,200);
    let pushedText = "";
    while (!pushedText.includes('"type":"theme"')) {
      const chunk = await liveReader.read();
      assert.equal(chunk.done, false, "SSE stream closed before theme update");
      pushedText += new TextDecoder().decode(chunk.value);
    }
    assert.match(pushedText,/#334455/);
    const liveInstall = await app.inject({method:"POST",url:"/templates/install",headers:{authorization:"Bearer "+tokens.accessToken},payload:{templateId:"glass"}});
    assert.equal(liveInstall.statusCode,200);
    let installEventText = "";
    while (!installEventText.includes('"type":"installed"')) {
      const chunk = await liveReader.read();
      assert.equal(chunk.done, false, "SSE stream closed before package install update");
      installEventText += new TextDecoder().decode(chunk.value);
    }
    assert.match(installEventText,/"glass"/);
    await liveReader.cancel();
    const activateStudio = await app.inject({method:"PUT",url:"/templates/preferences",headers:{authorization:"Bearer "+tokens.accessToken},payload:{public:"studio"}});
    assert.equal(activateStudio.statusCode,200);
    const rejectActiveUninstall = await app.inject({method:"DELETE",url:"/templates/install/studio",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.equal(rejectActiveUninstall.statusCode,409);
    await app.inject({method:"PUT",url:"/templates/preferences",headers:{authorization:"Bearer "+tokens.accessToken},payload:{public:"editorial"}});
    const uninstallStudio = await app.inject({method:"DELETE",url:"/templates/install/studio",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.equal(uninstallStudio.statusCode,200);
    assert.ok(!uninstallStudio.json().installedTemplates.includes("studio"));
    const publicAlphaUpdated = await app.inject({method:"GET",url:"/templates/public",headers:{host:"www.alpha.example.test"}});
    assert.equal(publicAlphaUpdated.json().selection.public,"editorial");
    assert.equal(publicAlphaUpdated.json().tokens["--bg"],"#334455");
    const publicBetaIsolated = await app.inject({method:"GET",url:"/templates/public",headers:{host:"beta.example.test"}});
    assert.equal(publicBetaIsolated.json().selection.public,"aurora");
    assert.equal(publicBetaIsolated.json().tokens["--bg"],"#080a12");

    const legacyLogin=await app.inject({method:"POST",url:"/auth/login",payload:{email:"legacy@example.com",password:"Test-password-12345",client:"dashboard"}});
    assert.equal(legacyLogin.statusCode,200);
    const legacyPreferences=await app.inject({method:"GET",url:"/templates/preferences",headers:{authorization:"Bearer "+legacyLogin.json().accessToken}});
    assert.deepEqual(legacyPreferences.json().selection,{public:"editorial",dashboard:"paper"});
    const betaLogin=await app.inject({method:"POST",url:"/auth/login",payload:{email:"beta@example.com",password:"Test-password-12345",client:"dashboard"}});
    assert.equal(betaLogin.statusCode,200);
    const betaTokens=betaLogin.json();
    const betaRead=await app.inject({method:"GET",url:"/templates/preferences",headers:{authorization:"Bearer "+betaTokens.accessToken}});
    assert.equal(betaRead.statusCode,200);
    assert.equal(betaRead.json().tenantId,"tenant-beta");
    assert.deepEqual(betaRead.json().selection,{public:"aurora",dashboard:"midnight"});
    assert.ok(!betaRead.json().installedTemplates.includes("studio"));
    const betaInstall = await app.inject({method:"POST",url:"/templates/install",headers:{authorization:"Bearer "+betaTokens.accessToken},payload:{templateId:"studio"}});
    assert.equal(betaInstall.statusCode,403);
    const betaDomainWrite=await app.inject({method:"PUT",url:"/tenants/domains",headers:{authorization:"Bearer "+betaTokens.accessToken},payload:{domains:["beta-new.example.test"]}});
    assert.equal(betaDomainWrite.statusCode,403);
    const conflictingDomain=await app.inject({method:"PUT",url:"/tenants/domains",headers:{authorization:"Bearer "+tokens.accessToken},payload:{domains:["beta.example.test"]}});
    assert.equal(conflictingDomain.statusCode,409);

    const betaTheme = await app.inject({method:"GET",url:"/templates/theme",headers:{authorization:"Bearer "+betaTokens.accessToken}});
    assert.equal(betaTheme.statusCode,200);
    assert.equal(betaTheme.json().tokens["--bg"],"#080a12");
    const betaWrite=await app.inject({method:"PUT",url:"/templates/preferences",headers:{authorization:"Bearer "+betaTokens.accessToken},payload:{public:"editorial"}});
    assert.equal(betaWrite.statusCode,403);
    const betaThemeWrite=await app.inject({method:"PUT",url:"/templates/theme",headers:{authorization:"Bearer "+betaTokens.accessToken},payload:{tokens:{"--bg":"#ffffff"}}});
    assert.equal(betaThemeWrite.statusCode,403);
    const alphaRecheck=await app.inject({method:"GET",url:"/templates/preferences",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.deepEqual(alphaRecheck.json().selection,{public:"editorial",dashboard:"paper"});
    await db.collection("memberships").updateOne({userId:"test-user",tenantId:"tenant-alpha"},{$set:{status:"suspended"}});
    const staleTenantToken=await app.inject({method:"GET",url:"/templates/preferences",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.equal(staleTenantToken.statusCode,403);
    await db.collection("memberships").updateOne({userId:"test-user",tenantId:"tenant-alpha"},{$set:{status:"active"}});

    const invalidTemplate = await app.inject({ method: "PUT", url: "/templates/preferences", headers: { authorization: "Bearer " + tokens.accessToken }, payload: { public: "remote-script" } });
    assert.equal(invalidTemplate.statusCode, 400);
    const unauthenticatedTemplates = await app.inject({ method: "GET", url: "/templates/preferences" });
    assert.equal(unauthenticatedTemplates.statusCode, 401);

    const companyList = await app.inject({method:"GET",url:"/companies",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.equal(companyList.statusCode,200);
    assert.ok(companyList.json().companies.some((company:{id:string;role:string})=>company.id==="tenant-alpha"&&company.role==="owner"));
    const createCompany = await app.inject({method:"POST",url:"/companies",headers:{authorization:"Bearer "+tokens.accessToken},payload:{name:"Second Company"}});
    assert.equal(createCompany.statusCode,201);
    const secondCompanyId=createCompany.json().company.id as string;
    const activateCompany=await app.inject({method:"POST",url:"/companies/"+secondCompanyId+"/activate",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.equal(activateCompany.statusCode,200);
    assert.equal(activateCompany.json().tenantId,secondCompanyId);
    const activeCompany=await app.inject({method:"GET",url:"/companies/active",headers:{authorization:"Bearer "+activateCompany.json().accessToken}});
    assert.equal(activeCompany.statusCode,200);
    assert.equal(activeCompany.json().company.id,secondCompanyId);
    const rejectCrossCompany=await app.inject({method:"POST",url:"/companies/"+secondCompanyId+"/activate",headers:{authorization:"Bearer "+betaTokens.accessToken}});
    assert.equal(rejectCrossCompany.statusCode,403);
    const addBetaMembership=await app.inject({method:"POST",url:"/companies/"+secondCompanyId+"/memberships",headers:{authorization:"Bearer "+activateCompany.json().accessToken},payload:{email:"beta@example.com",role:"member"}});
    assert.equal(addBetaMembership.statusCode,201);
    const memberList=await app.inject({method:"GET",url:"/companies/"+secondCompanyId+"/memberships",headers:{authorization:"Bearer "+activateCompany.json().accessToken}});
    assert.ok(memberList.json().memberships.some((member:{email:string;role:string})=>member.email==="beta@example.com"&&member.role==="member"));
    const betaActivateSecond=await app.inject({method:"POST",url:"/companies/"+secondCompanyId+"/activate",headers:{authorization:"Bearer "+betaTokens.accessToken}});
    assert.equal(betaActivateSecond.statusCode,200);
    assert.equal(betaActivateSecond.json().membership.role,"member");
    const betaSecondCompanyPreferences=await app.inject({method:"GET",url:"/templates/preferences",headers:{authorization:"Bearer "+betaActivateSecond.json().accessToken}});
    assert.equal(betaSecondCompanyPreferences.statusCode,200);
    assert.equal(betaSecondCompanyPreferences.json().tenantId,secondCompanyId);
    const betaCannotManageMembers=await app.inject({method:"POST",url:"/companies/"+secondCompanyId+"/memberships",headers:{authorization:"Bearer "+betaActivateSecond.json().accessToken},payload:{email:"legacy@example.com",role:"member"}});
    assert.equal(betaCannotManageMembers.statusCode,403);
    const updateBetaRole=await app.inject({method:"PUT",url:"/companies/"+secondCompanyId+"/memberships/test-user-beta",headers:{authorization:"Bearer "+activateCompany.json().accessToken},payload:{role:"manager"}});
    assert.equal(updateBetaRole.statusCode,200);
    assert.equal(updateBetaRole.json().membership.role,"manager");
    const betaOldRoleSession=await app.inject({method:"GET",url:"/companies/active",headers:{authorization:"Bearer "+betaActivateSecond.json().accessToken}});
    assert.equal(betaOldRoleSession.statusCode,401);
    const staleCompanyToken=await app.inject({method:"GET",url:"/templates/preferences",headers:{authorization:"Bearer "+tokens.accessToken}});
    assert.equal(staleCompanyToken.statusCode,401);

    const me = await app.inject({ method: "GET", url: "/auth/me", headers: { authorization: "Bearer " + tokens.accessToken } });
    assert.equal(me.statusCode, 200); assert.equal(me.json().authenticated, true);
    const refresh = await app.inject({ method: "POST", url: "/auth/refresh", payload: { refreshToken: tokens.refreshToken } });
    assert.equal(refresh.statusCode, 200);
    const refreshed = refresh.json(); assert.notEqual(refreshed.refreshToken, tokens.refreshToken);
    const replay = await app.inject({ method: "POST", url: "/auth/refresh", payload: { refreshToken: tokens.refreshToken } });
    assert.equal(replay.statusCode, 401);
    const logout = await app.inject({ method: "POST", url: "/auth/logout", headers: { authorization: "Bearer " + refreshed.accessToken }, payload: { refreshToken: refreshed.refreshToken } });
    assert.equal(logout.statusCode, 200);
    const afterLogout = await app.inject({ method: "POST", url: "/auth/refresh", payload: { refreshToken: refreshed.refreshToken } });
    assert.equal(afterLogout.statusCode, 401);
  } finally {
    await app.close();
    await client.db(dbName).dropDatabase();
    await client.close();
  }
});
